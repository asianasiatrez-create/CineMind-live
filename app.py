@app.route("/api/user/library/toggle", methods=["POST"])
def toggle_library():
    data = request.get_json() or {}
    username = data.get("username", "").strip().lower()
    lib_type = data.get("type")
    movie = data.get("movie", {})

    if not username or not lib_type or not movie:
        return jsonify({"success": False, "message": "Invalid payload."}), 400

    movie_id = movie.get("id")
    title = movie.get("title") or movie.get("name")
    poster = movie.get("poster") or ""
    vote_average = movie.get("vote_average", 0.0)

    conn = sqlite3.connect(DB_NAME)
    cursor = conn.cursor()
    table = "watchlist" if lib_type == "watchlist" else "favorites"

    cursor.execute(f"SELECT id FROM {table} WHERE username = ? AND movie_id = ?", (username, movie_id))
    exists = cursor.fetchone()

    if exists:
        cursor.execute(f"DELETE FROM {table} WHERE username = ? AND movie_id = ?", (username, movie_id))
        action = "removed"
    else:
        cursor.execute(f"INSERT OR REPLACE INTO {table} (username, movie_id, title, poster, vote_average) VALUES (?, ?, ?, ?, ?)",
                       (username, movie_id, title, poster, vote_average))
        action = "added"

    conn.commit()
    conn.close()
    return jsonify({"success": True, "action": action})

@app.route("/chat", methods=["POST"])
def chat():
    data = request.get_json() or {}
    user_message = data.get("message", "").strip().lower()
    profile = data.get("profile", {"name": "Movie Fan"})
    region = data.get("region", "PH")
    username = profile.get("name", "Movie Fan")

    if not user_message:
        return jsonify({"reply": f"Hey {username}! Tell me what kind of movie you're looking for.", "movies": []})

    try:
        # Fetch multiple pages to score against user prompt
        res = requests.get(f"https://api.themoviedb.org/3/movie/popular?api_key={TMDB_API_KEY}&page=1").json()
        results = res.get("results", [])
        res_2 = requests.get(f"https://api.themoviedb.org/3/movie/popular?api_key={TMDB_API_KEY}&page=2").json()
        if res_2.get("results"):
            results.extend(res_2.get("results"))

        stop_words = {"i", "want", "a", "movie", "set", "in", "with", "twist", "of", "and", "the", "to", "about", "an", "is", "that"}
        query_words = [w for w in user_message.split() if w not in stop_words and len(w) > 2]
        if not query_words:
            query_words = user_message.split()

        scored_movies = []
        for m in results:
            title = m.get("title", "").lower()
            overview = m.get("overview", "").lower()
            text_corpus = f"{title} {overview}"
            score = sum(1 for word in query_words if word in text_corpus)
            scored_movies.append((score, m))

        scored_movies.sort(key=lambda x: x[0], reverse=True)
        best_matches = [m for score, m in scored_movies if score > 0]
        if not best_matches:
            best_matches = [m for _, m in scored_movies[:4]]
        
        selected_pool = best_matches[:4]

        movies = []
        for m in selected_pool:
            movie_id = m.get("id")
            providers_url = f"https://api.themoviedb.org/3/movie/{movie_id}/watch/providers?api_key={TMDB_API_KEY}"
            prov_res = requests.get(providers_url).json().get("results", {})
            reg_prov = prov_res.get(region, prov_res.get("US", {}))
            flatrate = reg_prov.get("flatrate", [])
            platforms = [p.get("provider_name") for p in flatrate] if flatrate else ["TMDB VOD Catalog"]

            movies.append({
                "id": movie_id,
                "title": m.get("title"),
                "poster": f"https://image.tmdb.org/t/p/w500{m.get('poster_path')}" if m.get('poster_path') else "",
                "vote_average": m.get("vote_average", 0.0),
                "release_date": m.get("release_date", "2026"),
                "overview": m.get("overview") or "No overview available.",
                "match": 98,
                "platforms": platforms,
                "rationale": f"Matched via keyword matrix for '{user_message}'."
            })

        ai_reply = f"I scanned the cinematic records for your prompt, {username}! Here are the most relevant matches:"
    except Exception as e:
        movies = []
        ai_reply = "Neural search hit a temporary glitch. Try asking me again!"

    return jsonify({"reply": ai_reply, "movies": movies})

